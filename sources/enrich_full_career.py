def main() -> None:
    # 找已有文件（按 name）
    name_to_file = {}
    for p in CARDS.glob("*.md"):
        t = p.read_text(encoding="utf-8")
        m = re.search(r"^name:\s*(.+)$", t, re.M)
        if m:
            name_to_file[m.group(1).strip()] = p

    for person, meta in ENRICH.items():
        old = name_to_file.get(person)
        if old and old.exists():
            old.unlink()
        dyn = meta["dynasty"].replace("/", "_")
        src = "\n".join(
            f"  - book: {b}\n    juan: {j}\n    quote: 「{q}」" for b, j, q in meta["quotes"]
        )
        bio = "\n".join(f"{i}. {x}" for i, x in enumerate(meta["bio"], 1))
        rel = "\n".join(f"| {a} | {b} | {c} | 本传/考订 |" for a, b, c in meta["rels"])
        body = f"""---
id: {meta['id']}
name: {person}
style_name: {meta['style']}
dynasty: {dyn}
status: 待审
category: {meta['cat']}
origin: {meta['origin']}
birth: {meta['birth']}
death: {meta['death']}
shizhong_terms:
  - start: 阙
    end: 阙
    nature: {meta['nature']}
    evidence: 有明文
sources:
{src}
---

## 生平履历

{bio}

## 侍中任职前后

- {meta['nature']}

## 关系

| 对象 | 关系类型 | 说明 | 出处 |
|------|----------|------|------|
{rel}

## 校录备注

- 全履历重写：含侍中以外官职与关键事件
- 校录人/日期：待填
"""
        (CARDS / f"{person}_{dyn}.md").write_text(body, encoding="utf-8")
        print("enriched", person)

    # 重建 source/term for these
    con = sqlite3.connect(DB)
    cur = con.cursor()
    for person, meta in ENRICH.items():
        dyn = meta["dynasty"].replace("/", "_")
        path = CARDS / f"{person}_{dyn}.md"
        if not path.exists():
            continue
        # get pid
        text = path.read_text(encoding="utf-8")
        pid = re.search(r"^id:\s*(\S+)", text, re.M).group(1)
        for b, j, q in meta["quotes"]:
            cur.execute(
                "INSERT INTO source (book,juan,quote,path) VALUES (?,?,?,?)",
                (b, j, q, path.name),
            )
            cur.execute(
                """INSERT OR IGNORE INTO shizhong_term
                (person_id,start_ym,end_ym,nature,evidence,source_id,nature_primary)
                VALUES (?,?,?,?,?,?,?)""",
                (pid, "阙", "阙", meta["nature"][:120], "有明文", cur.lastrowid, "其他"),
            )
    con.commit()
