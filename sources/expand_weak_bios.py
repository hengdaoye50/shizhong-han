def find_card(name: str) -> Path | None:
    hits = list(CARDS.glob(f"{name}_*.md"))
    return hits[0] if hits else None


def replace_bio(path: Path, lines: list[str]) -> bool:
    raw = path.read_text(encoding="utf-8")
    body_lines = "\n".join(f"{i}. {t2s(s)}" for i, s in enumerate(lines, 1))
    if re.search(r"## 生平履历\n", raw):
        new = re.sub(
            r"## 生平履历\n+(.*?)(?=^## |\Z)",
            f"## 生平履历\n\n{body_lines}\n\n",
            raw,
            count=1,
            flags=re.S | re.M,
        )
    else:
        # 插在 frontmatter 后
        m = re.match(r"^(---\n.*?\n---\n)", raw, re.S)
        if not m:
            return False
        new = m.group(1) + f"\n## 生平履历\n\n{body_lines}\n" + raw[m.end() :]
    if new != raw:
        path.write_text(new, encoding="utf-8")
        return True
    return False


def main() -> None:
    if "--list" in sys.argv:
        for n in EXPAND:
            print(n)
        return
    ok = miss = 0
    for name, lines in EXPAND.items():
        p = find_card(name)
        if not p:
            print("MISS", name)
            miss += 1
            continue
        if replace_bio(p, lines):
            print("BIO", name, len(lines), p.name)
            ok += 1
        else:
            print("same", name)
    print("updated", ok, "missing_card", miss, "planned", len(EXPAND))


if __name__ == "__main__":
    main()
