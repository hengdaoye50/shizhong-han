def main() -> None:
    with QUEUE.open(encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    mined = defaultdict(list)
    un = []
    for r in rows:
        s = (r.get("sentence") or "").replace(" ", "")
        for key, person, flag in RULES:
            if key.replace(" ", "") in s:
                if flag == "U" or person.endswith("待考"):
                    un.append(r)
                else:
                    mined[person].append(r)
                break
    print("mined", len(mined), "ev", sum(len(v) for v in mined.values()), "un", len(un))
    for p, evs in sorted(mined.items(), key=lambda x: -len(x[1])):
        print(f"  {len(evs):2d} {p}")
    with OUT.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(
            f,
            fieldnames=["person", "cand_row", "book", "juan", "sentence", "source_file", "alias_in_sentence"],
        )
        w.writeheader()
        for p, evs in mined.items():
            for e in evs:
                w.writerow(
                    {
                        "person": p,
                        "cand_row": e.get("cand_row"),
                        "book": e.get("book"),
                        "juan": e.get("juan"),
                        "sentence": e.get("sentence"),
                        "source_file": e.get("source_file", ""),
                        "alias_in_sentence": "",
                    }
                )
    print("->", OUT)


if __name__ == "__main__":
    main()
