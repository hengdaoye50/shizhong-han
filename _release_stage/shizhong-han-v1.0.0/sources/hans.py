# str.translate 需要单字码位表；多字词进 _WORD
for _k, _v in list(_T2S.items()):
    if len(_k) != 1:
        _WORD[_k] = _v
        del _T2S[_k]
_TABLE = str.maketrans(_T2S)


def t2s(text: str) -> str:
    """繁体/异体 -> 简体。未识别字原样保留。"""
    if not text:
        return text
    s = text
    for a, b in _WORD.items():
        if a in s:
            s = s.replace(a, b)
    return s.translate(_TABLE)


def norm_quote(q: str) -> str:
    """引文归一：简体、去引号空白与占位符，供去重。"""
    if not q:
        return ""
    s = t2s(q)
    for ch in "「」『』\"\"''":
        s = s.replace(ch, "")
    s = re.sub(r"-\{后\}-|\{后\}|－\{后\}－", "后", s)
    s = re.sub(r"\s+", "", s)
    return s


def strip_cjk_punct(s: str) -> str:
    return re.sub(r"[，。、；：？！·…—（）《》「」『』\s\-{}]+", "", s or "")
